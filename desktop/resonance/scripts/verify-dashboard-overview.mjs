import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const dir='evidence/dashboard-overview';mkdirSync(dir,{recursive:true});
const app=await electron.launch({args:['.','--verify']});
const checks=[],check=(label,result)=>{assert.ok(result,label);checks.push(label);console.log(label);};
try {
 const p=await app.firstWindow(),errors=[];p.on('pageerror',e=>errors.push(e.message));
 const dashboard=()=>p.getByRole('button',{name:'Dashboard',exact:true});
 const settle=()=>p.waitForFunction(()=>document.querySelector('.dashboard-stage')?.dataset.motion==='settled');
 check('capsule has one Dashboard entry and no notification button',await dashboard().count()===1&&await p.getByRole('button',{name:'通知',exact:true}).count()===0);
 await dashboard().click();await settle();
 check('overview has no wordmark or minimize control',!await p.locator('.dashboard-heading').isVisible()&&await p.getByRole('button',{name:'收回胶囊',exact:true}).count()===0);
 check('quota summary exposes three same-line meters',await p.locator('.overview-meter').count()===3&&await p.locator('.overview-meter').evaluateAll(rows=>rows.every(r=>{const boxes=[...r.children].map(c=>c.getBoundingClientRect());return Math.max(...boxes.map(b=>b.y+b.height/2))-Math.min(...boxes.map(b=>b.y+b.height/2))<2;})));
 check('quota summary fits its card',await p.locator('[data-module="2"] .module-summary').evaluate(e=>e.scrollHeight<=e.clientHeight));
 check('existing notification cards live inside dashboard',await p.locator('.dashboard-notifications .result').count()===2&&await p.locator('.inbox').count()===1);
 await p.locator('.shell').screenshot({path:`${dir}/overview.png`});
 await dashboard().click();check('same button closes dashboard',await p.locator('.dashboard-surface').count()===0);
 await dashboard().click();await settle();
 await p.locator('[data-module="2"] .module-summary').click();await settle();
 check('quota detail hides notification area',await p.locator('.dashboard-notifications').count()===0);
 await p.getByRole('button',{name:'返回四个模块'}).click();await settle();
 await p.locator('.result').first().hover();await p.waitForTimeout(180);
 await p.getByRole('button',{name:'继续讨论周末徒步路线'}).click();
 await p.getByRole('textbox',{name:'回复周末徒步路线的内容'}).fill('测试原通知回复');
 await p.getByRole('button',{name:'发送通知回复（模拟）'}).click();
 await p.waitForFunction(()=>document.querySelector('.inline-reply-message')?.textContent.includes('未发送或执行真实任务'));
 check('notification reply remains available and simulated',true);
 await p.locator('.inline-reply-message').click();await p.keyboard.press('Escape');
 await p.locator('.result-main').first().click();
 check('notification detail opens inside dashboard',await p.locator('.dashboard-notifications').getByRole('region',{name:'结果详情'}).count()===1);
 await p.getByRole('button',{name:'关闭结果详情'}).click();
 await p.getByRole('button',{name:'外观与窗口选项',exact:true}).click();
 await p.getByRole('button',{name:'体验通知叠层'}).click();await settle();
 await p.getByRole('button',{name:/展开 \d+ 条通知/}).click();
 check('more notifications never render over two full cards',await p.locator('.result').count()===2);
 const more=p.getByRole('button',{name:/还有 \d+ 条/});await more.click();
 check('remaining notifications accessible without expanding panel',await p.getByRole('button',{name:'上一组'}).isVisible()&&await p.locator('.result').count()<=2);
 await p.getByRole('button',{name:'回到第一组'}).click();
 await p.getByRole('button',{name:'收起为叠层 · Esc'}).click();await p.waitForTimeout(450);
 check('original stack interaction retained',await p.locator('.inbox.is-stacked').count()===1);
 await p.getByRole('button',{name:/展开 \d+ 条通知/}).click();
 while(await p.locator('.result').count()) {const first=p.locator('.result').first();await first.hover();await first.locator('.result-dismiss').click();await p.waitForTimeout(400);}
 check('empty state retains reserved space',await p.getByText('暂时没有待查看的事项',{exact:true}).isVisible()&&(await p.locator('.dashboard-notifications').boundingBox()).height>=132);
 check('unread dot clears with notifications',await p.locator('.dashboard-unread').count()===0);
 await p.getByRole('button',{name:'进入 Live',exact:true}).click();await p.waitForTimeout(850);
 check('expanded capsule still has only one Dashboard button',await dashboard().count()===1&&await p.getByRole('button',{name:'通知',exact:true}).count()===0);
 check('transcript slit uses theme and thicker visible line',await p.locator('.transcript-trigger span').evaluate(e=>{const s=getComputedStyle(e);const probe=document.createElement('span');probe.style.color=s.getPropertyValue('--theme-color');document.body.append(probe);const color=getComputedStyle(probe).color;probe.remove();return s.backgroundColor===color&&parseFloat(s.height)>=2.5&&+s.opacity>=.7;}));
 await p.locator('.shell').screenshot({path:`${dir}/empty-live.png`});
 await p.getByRole('button',{name:'麦克风静音'}).click();check('microphone toggle retained',await p.getByRole('button',{name:'麦克风静音'}).getAttribute('aria-pressed')==='true');
 await p.getByRole('button',{name:'发消息',exact:true}).click();
 check('text mode also removes separate notification entry',await p.getByRole('button',{name:'通知',exact:true}).count()===0&&await dashboard().count()===1);
 check('no renderer errors',errors.length===0);
 writeFileSync(`${dir}/verification.json`,JSON.stringify({checks,errors},null,2));console.log(checks);
}finally{await app.close();}
