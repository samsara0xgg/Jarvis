import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
mkdirSync('evidence/notification-v2', { recursive: true });
const checks = [], app = await electron.launch({ args: ['.', '--verify'], cwd: process.cwd() });
const check = (label, pass) => { assert.ok(pass,label); checks.push(label); console.log(`PASS ${label}`); };
try {
  const page = await app.firstWindow();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.evaluate(() => localStorage.clear()); await page.reload(); await page.waitForSelector('canvas');
  const center = await page.locator('.wave-button').boundingBox();
  check('center is exactly 90 by 36, or 2.5:1', center.width === 90 && center.height === 36);
  check('side buttons and icons retain their original dimensions', await page.locator('.notification').evaluate(e => e.clientWidth === 38 && e.querySelector('svg').getBoundingClientRect().width === 20));
  await page.locator('.notification').hover(); await page.waitForTimeout(180);
  const split = () => page.locator('.control-row').evaluate(e => ({ left: getComputedStyle(e,'::before').content, right: getComputedStyle(e,'::after').content }));
  check('notification hover has no separators in the outer gaps', (await split()).left === 'none' && (await split()).right === 'none');
  await page.screenshot({ path:'evidence/notification-v2/notice-hover.png', omitBackground:true });
  await page.locator('.entry-button').hover(); await page.waitForTimeout(180);
  check('compose hover has no separators in the outer gaps', (await split()).left === 'none' && (await split()).right === 'none');
  await page.locator('.wave-button').hover(); await page.waitForTimeout(180);
  check('wave hover clears both internal separators', await page.locator('.voice-pill > .divider').evaluateAll(es => es.every(e => getComputedStyle(e).opacity === '0')));
  await page.locator('.voice-pill').click({ button:'right' });
  await page.getByRole('button',{name:'体验通知叠层'}).click();
  await page.mouse.move(1,1); await page.waitForTimeout(300);
  const cards = () => page.locator('.result').evaluateAll(es => es.map(e => { const r = e.getBoundingClientRect(); return { x:r.x,y:r.y,width:r.width,height:r.height,inert:e.inert }; }));
  const stacked = await cards();
  check('multiple notifications rest in an overlapping stack', stacked.length === 2 && stacked[1].y-stacked[0].y === 8 && stacked[1].width < stacked[0].width);
  check('covered notifications cannot receive keyboard input', stacked[1].inert);
  await page.screenshot({ path:'evidence/notification-v2/stacked.png', omitBackground:true });
  await page.getByRole('button',{name:'展开 2 条通知'}).hover(); await page.waitForTimeout(450);
  check('hover does not expand the stack', await page.locator('.inbox.is-stacked').count() === 1 && (await cards())[1].y === stacked[1].y);
  await page.getByRole('button',{name:'展开 2 条通知'}).click(); await page.waitForTimeout(250);
  const expanded = await cards();
  check('click expands both notifications with a gap', expanded[1].y-expanded[0].y === 63 && !expanded[1].inert);
  await page.locator('.result').first().hover(); await page.waitForTimeout(180);
  const reply = page.getByRole('button',{name:'继续讨论周末徒步路线'});
  const before = await reply.evaluate(e => getComputedStyle(e).backgroundColor);
  await reply.hover(); await page.waitForTimeout(180);
  check('reply gets a distinct hover surface and a small return glyph', await reply.evaluate((e,before) => getComputedStyle(e).backgroundColor !== before && e.querySelector('svg').getBoundingClientRect().width === 16, before));
  await page.screenshot({ path:'evidence/notification-v2/expanded-reply-hover.png', omitBackground:true });
  await reply.click();
  const input = page.getByRole('textbox',{name:'回复周末徒步路线的内容'});
  await input.waitFor();
  check('reply opens inside the original notification while keeping voice controls', await page.locator('.result.is-replying .inline-reply').count() === 1 && await page.locator('.shell.mode-voice').count() === 1);
  await input.fill('把第二条路线展开说说');
  await page.screenshot({ path:'evidence/notification-v2/inline-reply.png', omitBackground:true });
  await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('.inline-reply-message')?.textContent.includes('未发送或执行真实任务'));
  check('inline reply completes an explicitly simulated response', (await page.locator('.inline-reply-message').innerText()).includes('把第二条路线展开说说'));
  await page.getByRole('button',{name:'收起为叠层'}).click(); await page.waitForTimeout(220);
  check('explicit collapse restores the overlapping stack', await page.locator('.inbox.is-stacked').count() === 1);
  await page.getByRole('button',{name:'展开 2 条通知'}).focus(); await page.keyboard.press('Enter'); await page.waitForTimeout(220);
  check('keyboard activation can also expand the stack', await page.locator('.inbox.is-expanded').count() === 1);
  await page.getByRole('button',{name:'标记周末徒步路线已查看'}).click(); await page.waitForTimeout(250);
  check('removing the first card preserves the remaining notification', await page.locator('.result').count() === 1 && (await page.locator('.result').innerText()).includes('你设定的提醒'));
  check('no renderer errors', errors.length === 0);
  writeFileSync('evidence/notification-v2/verification.json',JSON.stringify({checks,stacked,expanded,errors},null,2));
} finally { await app.close(); }
